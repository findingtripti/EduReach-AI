
import pandas as pd
from sklearn.preprocessing import StandardScaler
from sklearn.mixture import GaussianMixture
from sklearn.metrics import adjusted_rand_score
from pathlib import Path

INPUT_FILE = "edureach_improved_accessibility.csv"
OUTPUT_FILE = "edureach_gmm_evaluation_report.txt"

FEATURES = [
    "Nearest_School_Distance_km",
    "Has_School",
    "Has_PS",
    "Has_UPS",
    "Has_Composite",
    "Has_Madhyamik",
    "School_Count",
]


def main():
    df = pd.read_csv(INPUT_FILE)

    if df[FEATURES].isnull().any().any():
        raise ValueError("Missing values found in GMM input features.")

    X = StandardScaler().fit_transform(df[FEATURES])
    report = []

    report.extend([
        "EDUREACH AI - GMM MODEL EVALUATION",
        "=" * 55,
        f"Dataset: {INPUT_FILE}",
        f"Villages: {len(df)}",
        f"Input features: {len(FEATURES)}",
        "Missing values in input features: 0",
        "",
        "1. MODEL SELECTION: BIC AND AIC",
        "-" * 55,
        "Lower BIC/AIC values are preferred among tested models.",
    ])

    for k in range(2, 6):
        model = GaussianMixture(n_components=k, random_state=42)
        model.fit(X)
        report.append(
            f"k={k} | BIC={model.bic(X):.2f} | "
            f"AIC={model.aic(X):.2f} | "
            f"Converged={model.converged_}"
        )

    report.extend(["", "2. CLUSTER PROFILES", "-" * 55])

    for k in [3, 5]:
        model = GaussianMixture(n_components=k, random_state=42)
        result = df.copy()
        result["Cluster"] = model.fit_predict(X)

        summary = result.groupby("Cluster").agg(
            Villages=("Village", "count"),
            Avg_Distance_km=("Nearest_School_Distance_km", "mean"),
            Villages_With_School=("Has_School", "sum"),
            Avg_School_Count=("School_Count", "mean"),
            Avg_Accessibility=("Accessibility_Index", "mean"),
        ).round(2)

        report.append(f"\n{k}-cluster model:")
        report.append(summary.to_string())

    report.extend([
        "",
        "3. RANDOM-SEED STABILITY (ADJUSTED RAND INDEX)",
        "-" * 55,
        "ARI=1 means identical groupings; values near 0 indicate "
        "chance-level agreement.",
    ])

    for k in [3, 5]:
        label_sets = []

        for seed in [0, 7, 21, 42, 99]:
            model = GaussianMixture(
                n_components=k,
                random_state=seed,
                n_init=1,
            )
            label_sets.append(model.fit_predict(X))

        scores = [
            adjusted_rand_score(label_sets[i], label_sets[j])
            for i in range(len(label_sets))
            for j in range(i + 1, len(label_sets))
        ]

        report.append(
            f"k={k} | Mean ARI={sum(scores) / len(scores):.3f} | "
            f"Min ARI={min(scores):.3f} | Max ARI={max(scores):.3f}"
        )

    report.extend([
        "",
        "4. INTERPRETATION AND LIMITATIONS",
        "-" * 55,
        "- Five clusters had lower BIC/AIC than three in the tested range.",
        "- Three clusters provide a simpler dashboard interpretation.",
        "- Five clusters create extra subgroups that need practical review.",
        "- Random-seed tests showed some variation in assignments.",
        "- Has_School and school-type indicators are model input features.",
        "- This is unsupervised clustering, not a supervised accuracy test.",
        "- Straight-line distance does not equal actual road travel distance.",
        "- Cluster labels may change with data, features, or model settings.",
        "",
        "Current dashboard choice: retain 3 clusters for simplicity; "
        "document the 5-cluster alternative.",
        "",
        "Generated by evaluate_gmm.py",
    ])

    Path(OUTPUT_FILE).write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"\nReport saved to: {OUTPUT_FILE}")


if __name__ == "__main__":
    main()